// Sources/PurahUI/Plugins/PurahPluginScaffoldGenerator.swift
import Foundation
import AppKit
import PurahCore

public typealias ScreenEdge = MountEdge

public struct PurahPluginScaffoldOptions: Sendable, Equatable {
    public var pluginId: String
    public var displayName: String
    public var moduleName: String
    public var author: String
    public var description: String
    public var systemIcon: String
    public var defaultEdge: ScreenEdge
    public var defaultColorHex: String

    public init(
        pluginId: String,
        displayName: String,
        moduleName: String? = nil,
        author: String = NSFullUserName(),
        description: String = "A tactile ambient Purah plugin.",
        systemIcon: String = "puzzlepiece.extension",
        defaultEdge: ScreenEdge = .left,
        defaultColorHex: String = "#00D1FF"
    ) {
        self.pluginId = pluginId
        self.displayName = displayName
        self.moduleName = moduleName.map { PurahPluginScaffoldGenerator.sanitizedModuleName(from: $0) }
            ?? PurahPluginScaffoldGenerator.sanitizedModuleName(from: displayName)
        self.author = author.isEmpty ? "Developer" : author
        self.description = description
        self.systemIcon = systemIcon.isEmpty ? "puzzlepiece.extension" : systemIcon
        self.defaultEdge = defaultEdge
        self.defaultColorHex = defaultColorHex.isEmpty ? "#00D1FF" : defaultColorHex
    }
}

@MainActor
public enum PurahPluginScaffoldGenerator {

    nonisolated public static func sanitizedModuleName(from text: String) -> String {
        let cleaned = text.components(separatedBy: CharacterSet.alphanumerics.inverted)
            .filter { !$0.isEmpty }
            .map { $0.prefix(1).uppercased() + $0.dropFirst() }
            .joined()
        if cleaned.isEmpty {
            return "PurahPlugin"
        }
        if let first = cleaned.first, first.isNumber {
            return "P" + cleaned
        }
        return cleaned
    }

    public static func generatePackage(
        options: PurahPluginScaffoldOptions,
        in parentDirectory: URL
    ) throws -> URL {
        let fileManager = FileManager.default
        let moduleName = options.moduleName.isEmpty ? sanitizedModuleName(from: options.displayName) : options.moduleName
        let packageDir = parentDirectory.appendingPathComponent(moduleName, isDirectory: true)
        let sourcesDir = packageDir.appendingPathComponent("Sources/\(moduleName)", isDirectory: true)

        try fileManager.createDirectory(at: sourcesDir, withIntermediateDirectories: true)

        // 1. Package.swift
        let packageSwiftContent = generatePackageSwift(moduleName: moduleName)
        let packageSwiftURL = packageDir.appendingPathComponent("Package.swift")
        try packageSwiftContent.write(to: packageSwiftURL, atomically: true, encoding: .utf8)

        // 2. PurahExternalPluginSDK.swift
        let sdkContent = try canonicalSDKSource()
        let sdkURL = sourcesDir.appendingPathComponent("PurahExternalPluginSDK.swift")
        try sdkContent.write(to: sdkURL, atomically: true, encoding: .utf8)

        // 3. <moduleName>.swift
        let pluginSwiftContent = generatePluginSource(options: options, moduleName: moduleName)
        let pluginSwiftURL = sourcesDir.appendingPathComponent("\(moduleName).swift")
        try pluginSwiftContent.write(to: pluginSwiftURL, atomically: true, encoding: .utf8)

        return packageDir
    }

    private static func generatePackageSwift(moduleName: String) -> String {
        """
        // swift-tools-version: 6.0
        import PackageDescription

        let package = Package(
            name: "\(moduleName)",
            platforms: [
                .macOS(.v14)
            ],
            products: [
                .library(
                    name: "\(moduleName)",
                    type: .dynamic,
                    targets: ["\(moduleName)"]
                )
            ],
            targets: [
                .target(
                    name: "\(moduleName)",
                    dependencies: []
                )
            ]
        )
        """
    }

    private static func generatePluginSource(options: PurahPluginScaffoldOptions, moduleName: String) -> String {
        let edgeString = options.defaultEdge == .left ? "left" : "right"
        return """
        // \(moduleName).swift
        // Generated by Purah Plugin Scaffold Generator
        import SwiftUI
        import AppKit

        // MARK: - State Container
        @MainActor
        final class \(moduleName)State: ObservableObject {
            static let shared = \(moduleName)State()

            @Published var count: Int = 0
            @Published var statusMessage: String = "Ready"

            init() {}

            func increment() {
                count += 1
            }

            func reset() {
                count = 0
            }
        }

        // MARK: - Drawer View
        struct \(moduleName)DrawerView: View {
            @ObservedObject private var state = \(moduleName)State.shared

            var body: some View {
                VStack(spacing: 12) {
                    Spacer()

                    HStack(spacing: 12) {
                        ZStack {
                            Circle()
                                .fill(Color(hex: "\(options.defaultColorHex)").opacity(0.18))
                                .frame(width: 44, height: 44)
                            Image(systemName: "\(options.systemIcon)")
                                .font(.system(size: 20, weight: .semibold))
                                .foregroundColor(Color(hex: "\(options.defaultColorHex)"))
                        }

                        VStack(alignment: .leading, spacing: 2) {
                            Text("\(options.displayName)")
                                .font(.system(size: 14, weight: .bold, design: .rounded))
                                .foregroundColor(.primary)
                            Text("Counter: \\(state.count)")
                                .font(.system(size: 11, design: .monospaced))
                                .foregroundColor(.secondary)
                        }

                        Spacer()
                    }
                    .padding(10)
                    .background(Color.primary.opacity(0.04))
                    .cornerRadius(8)

                    HStack(spacing: 8) {
                        Button {
                            state.increment()
                            PurahHostBridge.shared.performHaptic(pluginId: "\(options.pluginId)", type: "alignment")
                        } label: {
                            HStack(spacing: 4) {
                                Image(systemName: "plus")
                                Text("Increment")
                            }
                            .font(.system(size: 11, weight: .semibold))
                            .frame(maxWidth: .infinity)
                            .padding(.vertical, 6)
                            .background(Color(hex: "\(options.defaultColorHex)"))
                            .foregroundColor(.white)
                            .cornerRadius(6)
                        }
                        .buttonStyle(.plain)

                        Button {
                            state.reset()
                        } label: {
                            Text("Reset")
                                .font(.system(size: 11, weight: .medium))
                                .padding(.horizontal, 12)
                                .padding(.vertical, 6)
                                .background(Color.primary.opacity(0.06))
                                .foregroundColor(.secondary)
                                .cornerRadius(6)
                        }
                        .buttonStyle(.plain)
                    }

                    Spacer()
                }
                .padding(12)
                .frame(maxWidth: .infinity, maxHeight: .infinity)
            }
        }

        // MARK: - C-ABI Entry Points

        private let manifestJSON = \"\"\"
        {
            "id": "\(options.pluginId)",
            "displayName": "\(options.displayName)",
            "author": "\(options.author)",
            "description": "\(options.description)",
            "version": "1.0.0",
            "systemIcon": "\(options.systemIcon)",
            "defaultColorHex": "\(options.defaultColorHex)",
            "defaultEdge": "\(edgeString)",
            "category": "Lightweight",
            "supportedDrawerModes": ["composite"],
            "minimumDrawerHeight": 120.0,
            "preferredDrawerHeight": 280.0
        }
        \"\"\"

        @MainActor
        @_cdecl("purahPluginABIVersion")
        public func purahPluginABIVersion() -> UnsafePointer<CChar> {
            return ("1" as NSString).utf8String!
        }

        @MainActor
        @_cdecl("purahPluginManifestJSON")
        public func purahPluginManifestJSON() -> UnsafePointer<CChar> {
            return (manifestJSON as NSString).utf8String!
        }

        @MainActor
        @_cdecl("purahSetHostActionBridge")
        public func purahSetHostActionBridge(callback: PurahABIHostActionCallback) {
            PurahHostBridge.shared.registerCallback(callback)
        }

        @MainActor
        @_cdecl("purahRailBarStateJSON")
        public func purahRailBarStateJSON(contextJSON: UnsafePointer<CChar>) -> UnsafePointer<CChar>? {
            _ = PurahExternalContext.decode(from: contextJSON)
            return PurahExternalRailBarState(
                style: "solid",
                colorHex: "\(options.defaultColorHex)",
                hasContent: true,
                ratio: 1.0
            ).toCString()
        }

        @MainActor
        @_cdecl("purahHeaderAccessoryJSON")
        public func purahHeaderAccessoryJSON(contextJSON: UnsafePointer<CChar>) -> UnsafePointer<CChar>? {
            _ = PurahExternalContext.decode(from: contextJSON)
            return PurahExternalHeaderAccessory.badge("Active", colorHex: "\(options.defaultColorHex)").toCString()
        }

        @MainActor
        @_cdecl("purahSettingsSchemaJSON")
        public func purahSettingsSchemaJSON(contextJSON: UnsafePointer<CChar>) -> UnsafePointer<CChar>? {
            _ = PurahExternalContext.decode(from: contextJSON)
            let sections: [PurahExternalSettingSection] = [
                PurahExternalSettingSection(
                    id: "general",
                    title: "General Settings",
                    icon: "gearshape.fill",
                    items: [
                        PurahExternalSettingItem.toggle(
                            id: "enable_haptics",
                            title: "Haptic Feedback",
                            subtitle: "Play sensory haptic when clicking buttons",
                            isOn: true
                        )
                    ]
                )
            ]
            return PurahExternalSettingSection.encodeListToCString(sections)
        }

        @MainActor
        @_cdecl("purahOnSettingChanged")
        public func purahOnSettingChanged(contextJSON: UnsafePointer<CChar>, key: UnsafePointer<CChar>, value: UnsafePointer<CChar>) {
            _ = PurahExternalContext.decode(from: contextJSON)
            let k = String(cString: key)
            let v = String(cString: value)
            _ = (k, v)
        }

        @MainActor
        @_cdecl("purahCreateDrawerView")
        public func purahCreateDrawerView() -> UnsafeMutableRawPointer? {
            return PurahViewHost.retain(\(moduleName)DrawerView())
        }

        @MainActor
        @_cdecl("purahCreateDrawerViewWithContext")
        public func purahCreateDrawerViewWithContext(contextJSON: UnsafePointer<CChar>) -> UnsafeMutableRawPointer? {
            _ = PurahExternalContext.decode(from: contextJSON)
            return PurahViewHost.retain(\(moduleName)DrawerView())
        }

        @MainActor
        @_cdecl("purahUpdateContext")
        public func purahUpdateContext(viewPtr: UnsafeMutableRawPointer, contextJSON: UnsafePointer<CChar>) {
            _ = PurahExternalContext.decode(from: contextJSON)
        }
        """
    }

    static func canonicalSDKSource() throws -> String {
        let bundleURL = Bundle.module.url(
            forResource: "PurahExternalPluginSDK",
            withExtension: "swift",
            subdirectory: "Resources"
        )
        guard let bundleURL else {
            throw PluginDynamicLoadError.fileNotFound("PurahExternalPluginSDK.swift in PurahUI resources")
        }
        return try String(contentsOf: bundleURL, encoding: .utf8)
    }
}
