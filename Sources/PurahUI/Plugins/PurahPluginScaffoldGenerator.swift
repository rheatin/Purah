// Sources/PurahUI/Plugins/PurahPluginScaffoldGenerator.swift
import Foundation
import AppKit
import PurahCore

public typealias ScreenEdge = MountEdge

public struct PurahPluginScaffoldOptions: Sendable, Equatable {
    public var pluginId: String
    public var displayName: String
    public var moduleName: String
    public var author: String
    public var description: String
    public var systemIcon: String
    public var defaultEdge: ScreenEdge
    public var defaultColorHex: String

    public init(
        pluginId: String,
        displayName: String,
        moduleName: String? = nil,
        author: String = NSFullUserName(),
        description: String = "A tactile ambient Purah plugin.",
        systemIcon: String = "puzzlepiece.extension",
        defaultEdge: ScreenEdge = .left,
        defaultColorHex: String = "#00D1FF"
    ) {
        self.pluginId = pluginId
        self.displayName = displayName
        self.moduleName = moduleName.map { PurahPluginScaffoldGenerator.sanitizedModuleName(from: $0) }
            ?? PurahPluginScaffoldGenerator.sanitizedModuleName(from: displayName)
        self.author = author.isEmpty ? "Developer" : author
        self.description = description
        self.systemIcon = systemIcon.isEmpty ? "puzzlepiece.extension" : systemIcon
        self.defaultEdge = defaultEdge
        self.defaultColorHex = defaultColorHex.isEmpty ? "#00D1FF" : defaultColorHex
    }
}

@MainActor
public enum PurahPluginScaffoldGenerator {

    nonisolated public static func sanitizedModuleName(from text: String) -> String {
        let cleaned = text.components(separatedBy: CharacterSet.alphanumerics.inverted)
            .filter { !$0.isEmpty }
            .map { $0.prefix(1).uppercased() + $0.dropFirst() }
            .joined()
        if cleaned.isEmpty {
            return "PurahPlugin"
        }
        if let first = cleaned.first, first.isNumber {
            return "P" + cleaned
        }
        return cleaned
    }

    public static func generatePackage(
        options: PurahPluginScaffoldOptions,
        in parentDirectory: URL
    ) throws -> URL {
        let fileManager = FileManager.default
        let moduleName = options.moduleName.isEmpty ? sanitizedModuleName(from: options.displayName) : options.moduleName
        let packageDir = parentDirectory.appendingPathComponent(moduleName, isDirectory: true)
        let sourcesDir = packageDir.appendingPathComponent("Sources/\(moduleName)", isDirectory: true)

        try fileManager.createDirectory(at: sourcesDir, withIntermediateDirectories: true)

        // 1. Package.swift
        let packageSwiftContent = generatePackageSwift(moduleName: moduleName)
        let packageSwiftURL = packageDir.appendingPathComponent("Package.swift")
        try packageSwiftContent.write(to: packageSwiftURL, atomically: true, encoding: .utf8)

        // 2. PurahExternalPluginSDK.swift
        let sdkContent = resolveSDKSource()
        let sdkURL = sourcesDir.appendingPathComponent("PurahExternalPluginSDK.swift")
        try sdkContent.write(to: sdkURL, atomically: true, encoding: .utf8)

        // 3. <moduleName>.swift
        let pluginSwiftContent = generatePluginSource(options: options, moduleName: moduleName)
        let pluginSwiftURL = sourcesDir.appendingPathComponent("\(moduleName).swift")
        try pluginSwiftContent.write(to: pluginSwiftURL, atomically: true, encoding: .utf8)

        return packageDir
    }

    private static func generatePackageSwift(moduleName: String) -> String {
        """
        // swift-tools-version: 6.0
        import PackageDescription

        let package = Package(
            name: "\(moduleName)",
            platforms: [
                .macOS(.v14)
            ],
            products: [
                .library(
                    name: "\(moduleName)",
                    type: .dynamic,
                    targets: ["\(moduleName)"]
                )
            ],
            targets: [
                .target(
                    name: "\(moduleName)",
                    dependencies: []
                )
            ]
        )
        """
    }

